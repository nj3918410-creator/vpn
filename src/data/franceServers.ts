export function generateRandomFrenchIp(cityHint?: string): { ip: string; city: string; isp: string } {
  let pool = FRENCH_IP_PREFIXES;
  if (cityHint) {
    const matched = FRENCH_IP_PREFIXES.filter((p) => p.city.toLowerCase() === cityHint.toLowerCase());
    if (matched.length > 0) pool = matched;
  }
  const selected = pool[Math.floor(Math.random() * pool.length)];
  const lastOctet = Math.floor(Math.random() * 253) + 2;
  return {
    ip: `${selected.prefix}.${lastOctet}`,
    city: selected.city,
    isp: selected.isp,
  };
}
